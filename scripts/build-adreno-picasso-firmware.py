#!/usr/bin/env python3
"""Generate the embedded A620 GPU firmware arrays for the NativeAdrenoPicasso probe.

The repository never carries vendor blobs. This script turns the files staged
in ADRENO620_FW_DIR (default /tmp/picasso-gpu-fw) into one C translation unit
that defines native_adreno620_set_embedded_firmware(): it calls the probe's
native_adreno_set_firmware() with pointers to the arrays. Missing files produce
empty arrays (size 0), so the build stays deterministic and probe stage 3
reports "blobs were not staged" instead of failing to link.

Files used (the board's default SQE/GMU pair is a630_sqe.fw + a650_gmu.bin;
a650_sqe.fw is embedded too so the probe's alternate can be selected later):
  a650_gmu.bin, a630_sqe.fw, a650_sqe.fw, a620_zap.mdt, a620_zap.b00..b02
"""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = Path(os.environ.get('ADRENO620_FW_OUT') or
               (ROOT / 'build/adreno-picasso'))
FW_DIR = Path(os.environ.get('ADRENO620_FW_DIR') or '/tmp/picasso-gpu-fw')

FILES = {
    'gmu': 'a650_gmu.bin',
    # The vendor a620 core entry (adreno_gpu_core_a620) and mainline's a620
    # series both pair this GPU with a650_sqe.fw: a620 is an A650 derivative.
    'sqe': 'a650_sqe.fw',
    'sqe_alt': 'a630_sqe.fw',
    'zap_mdt': 'a620_zap.mdt',
    'zap_b00': 'a620_zap.b00',
    'zap_b01': 'a620_zap.b01',
    'zap_b02': 'a620_zap.b02',
}


def emit(name, data, lines):
    symbol = f'native_adreno620_fw_{name}'
    lines.append(f'const uint8_t {symbol}[] = {{')
    if data:
        for start in range(0, len(data), 16):
            lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[start:start + 16]) + ',')
    else:
        # A zero-length array is not valid C; one dummy byte with a zero size keeps the symbol defined.
        lines.append('    0x00,')
    lines.append('};')
    lines.append(f'const uint32_t {symbol}_size = {len(data)}u;')


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by scripts/build-adreno-picasso-firmware.py; no vendor blob is committed. */',
             '#include "Adreno620Probe.h"',
             '#include <stddef.h>',
             '#include <stdint.h>', '']
    sizes = {}
    for name, filename in FILES.items():
        path = FW_DIR / filename
        data = path.read_bytes() if path.is_file() else b''
        sizes[name] = len(data)
        emit(name, data, lines)
        print(f'adreno620 fw {name:8s} {filename:16s} {len(data)} bytes'
              + ('' if data else ' (missing)'))
    lines += [
        '',
        'void native_adreno620_set_embedded_firmware(void)',
        '{',
        '    const struct native_adreno620_firmware fw = {',
        '        native_adreno620_fw_gmu, native_adreno620_fw_gmu_size,',
        '        native_adreno620_fw_sqe, native_adreno620_fw_sqe_size,',
        '        native_adreno620_fw_zap_mdt, native_adreno620_fw_zap_mdt_size,',
        '        { native_adreno620_fw_zap_b00, native_adreno620_fw_zap_b01, native_adreno620_fw_zap_b02 },',
        '        { native_adreno620_fw_zap_b00_size, native_adreno620_fw_zap_b01_size,',
        '          native_adreno620_fw_zap_b02_size },',
        '    };',
        '    native_adreno_set_firmware(&fw);',
        '}',
        '',
    ]
    target = OUT_DIR / 'adreno620_embedded_firmware.c'
    target.write_text('\n'.join(lines))
    print(f'adreno620 fw: {target}')
    present = sum(1 for value in sizes.values() if value)
    print(f'adreno620 fw: {present}/{len(FILES)} files embedded')


if __name__ == '__main__':
    main()

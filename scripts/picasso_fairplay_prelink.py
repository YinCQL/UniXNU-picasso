def require(value, message):
    if not value:
        raise ValueError(message)

def read(native, data, image, va, size):
    at = native.backed_offset(image['segments'], va, size, len(data))
    return data[at:at + size]

def inspect(native, emitter, data):
    require(hashlib.sha256(data).hexdigest() == DONOR_SHA256, 'FairPlay donor differs')
    image = native.macho(data)
    info = next(s for s in image['segments'] if s['name'] == '__PRELINK_INFO')
    entries = native.unserialize_xml(read(native, data, image, info['va'], info['filesize']))
    entry = next(e for e in entries['_PrelinkInfoDictionary'] if e['CFBundleIdentifier'] == PROVIDER)
    address = entry['_PrelinkExecutableLoadAddr']
    module = native.macho(data, native.backed_offset(image['segments'], address, 32, len(data)))
    code = next(s for s in module['segments'] if s['name'] == '__TEXT_EXEC')
    blob = read(native, data, image, code['va'], code['filesize'])
    require(hashlib.sha256(blob).hexdigest() == CODE_SHA256, 'FairPlay executable differs')
    exports = native.exports(data, image)
    require(len(BINDINGS) == 36 and len(OPAQUE_WORDS) == 144, 'FairPlay inventory differs')
    sites = {site: (target, base, offset, names) for site, target, base, offset, names in BINDINGS}
    require(len(sites) == len(BINDINGS), 'Duplicate encoded binding site')
    for site, (target, base, offset, names) in sites.items():
        require(any(s['name'] == '__DATA_CONST' and s['va'] <= site < site + 8 <= s['va'] + s['filesize'] for s in module['segments']), 'Encoded binding outside provider')
        require(struct.unpack('<Q', read(native, data, image, site, 8))[0] == target and target == base + offset, 'Encoded provider pointer differs')
        require(tuple(exports.get(base, ())) == names and offset in (2, 3, 7), 'Encoded provider export differs')
    opaque = {pc: word for pc, word, _, _ in OPAQUE_WORDS}
    require(len(opaque) == len(OPAQUE_WORDS), 'Duplicate opaque word')
    for pc, word, previous, digest in OPAQUE_WORDS:
        off = pc - code['va']
        require(16 <= off <= len(blob) - 20 and off % 4 == 0, 'Opaque word outside provider code')
        require(struct.unpack_from('<II', blob, off - 4) == (previous, word), 'Opaque word or predecessor differs')
        require(previous & 0xfffffc1f == 0xd61f0000 or previous & 0xfc000000 == 0x14000000, 'Opaque word permits fallthrough')
        require(hashlib.sha256(blob[off - 16:off + 20]).hexdigest() == digest, 'Opaque word context differs')
    for off in range(0, len(blob) - 3, 4):
        decoded = emitter.pc_relative_target(struct.unpack_from('<I', blob, off)[0], code['va'] + off)
        require(not decoded or decoded[1] or decoded[0] not in opaque, 'Direct edge enters opaque word')
    packed = entries['_PrelinkLinkKASLROffsets']
    count, = struct.unpack_from('<I', packed)
    require(len(packed) == 4 + 4 * count, 'Relocation table extent differs')
    base = next(s['va'] for s in image['segments'] if s['name'] == '__PRELINK_TEXT')
    found = set()
    for delta in struct.unpack_from('<' + str(count) + 'I', packed, 4):
        site = base + delta
        if not any(s['va'] <= site < site + 8 <= s['va'] + s['size'] for s in module['segments']):
            continue
        target, = struct.unpack('<Q', read(native, data, image, site, 8))
        require(target not in opaque, 'Relocated table enters opaque word')
        if site in sites:
            require(target == sites[site][0], 'Encoded relocation differs')
            found.add(site)
    require(found == set(sites), 'Encoded bindings missing from relocation table')
    return image, module, code, opaque

def emit(native, emitter, kernel, original, roots, slide, initializers):
    require(roots.count(PROVIDER) == 1, 'Original FairPlay provider root required exactly once')
    image, module, code, opaque = inspect(native, emitter, original)
    normal_binding = native.unique_kernel_binding
    normal_inventory = emitter.instruction_inventory
    encoded = {target: (base, offset, names) for _, target, base, offset, names in BINDINGS}
    used = set()
    def binding(address, original_exports, native_symbols):
        if address not in encoded:
            return normal_binding(address, original_exports, native_symbols)
        base, offset, names = encoded[address]
        require(tuple(original_exports.get(base, ())) == names, 'Encoded export aliases differ')
        used.add(address)
        # Preserve the original offset; the original consumer decodes it.
        return normal_binding(base, original_exports, native_symbols) + offset
    def inventory(data, parent, modules):
        require(data is original and PROVIDER in modules and modules[PROVIDER] == module, 'Provider inspection scope differs')
        others = {key: value for key, value in modules.items() if key != PROVIDER}
        result = normal_inventory(data, parent, others)
        extents = [s for value in modules.values() for s in value['segments'] if s['size'] and s['name'] != '__LINKEDIT']
        blob = read(native, original, image, code['va'], code['filesize'])
        count = 0
        for off in range(0, len(blob) - 3, 4):
            pc = code['va'] + off
            word, = struct.unpack_from('<I', blob, off)
            if pc in opaque:
                require(word == opaque[pc], 'Opaque word changed during inventory')
                continue
            decoded = emitter.pc_relative_target(word, pc)
            if decoded is None:
                continue
            target, page = decoded
            internal = any((s['va'] & ~4095) <= target < emitter.align(s['va'] + s['size']) for s in extents) if page else any(s['va'] <= target < s['va'] + s['size'] for s in extents)
            require(internal, 'Unqualified FairPlay PC-relative encoding at ' + hex(pc))
            count += 1
        result['pc_relative_encodings_preserved'] += count
        result['known_inline_data'] += [{'module': PROVIDER, 'va': pc, 'size': 4, 'sha256': hashlib.sha256(struct.pack('<I', word)).hexdigest()} for pc, word in opaque.items()]
        return result
    try:
        native.unique_kernel_binding = binding
        emitter.instruction_inventory = inventory
        candidate, plan = emitter.emit(kernel, original, roots, slide, initializers)
    finally:
        native.unique_kernel_binding = normal_binding
        emitter.instruction_inventory = normal_inventory
    require(used == set(encoded), 'Encoded mapping was incomplete')
    selected = {p['site']: p for p in plan['bindings']}
    for site, target, base, offset, names in BINDINGS:
        require(selected[site]['module'] == PROVIDER and selected[site]['target'] == target, 'Encoded mapping used outside provider')
    candidate_image = native.macho(candidate)
    require(read(native, candidate, candidate_image, code['va'] + slide, code['filesize']) == read(native, original, image, code['va'], code['filesize']), 'Original FairPlay instructions changed')
    plan['picasso_fairplay_prelink'] = dict(schema=1, provider=PROVIDER, original_code_sha256=CODE_SHA256,
        encoded_binding_sites=len(BINDINGS), exact_opaque_words=len(OPAQUE_WORDS),
        instructions_modified=False, source_inputs_modified=False, direct_edges_verified=True,
        register_dataflow_qualified=False, runtime_qualified=False)
    return candidate, plan

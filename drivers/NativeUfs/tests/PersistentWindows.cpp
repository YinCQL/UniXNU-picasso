#include <cstdlib>

static uint32_t testMode, testReserveMiB, testLog;
static bool PE_parse_boot_argn(const char *name, void *value, unsigned size)
{
  assert(size == sizeof(uint32_t));
  uint32_t result;
  if (!strcmp(name, "sheng-data-persist")) result = testMode;
  else if (!strcmp(name, "sheng-log-reserve")) result = testReserveMiB;
  else if (!strcmp(name, "sheng-log")) result = testLog;
  else return false;
  memcpy(value, &result, size);
  return true;
}

// Generated byte-for-byte from NativeUfs.cpp by the host checker. This is not
// a second implementation of store placement, mode checks or aux capacity.
#include "PersistentBoard.inc"

static void geometry(uint64_t partition, uint64_t imageBlocks)
{
  reset();
  gStoreGeometry = {true, 8192, 8192 + partition - 1, imageBlocks * 4096, 2, 0, 0, 128};
  gStoreRegionFirst = gStoreRegionBlocks = gAuxRegionFirst = gAuxRegionBlocks = 0;
  gLogRegionFirst = gLogRegionBlocks = 0;
}

static void checkWindowOrders()
{
  using Opener = bool (*)(uint64_t, uint64_t);
  const Opener open[] = {hostStoreOpen, hostAuxOpen, hostLogOpen};
  unsigned order[] = {0, 1, 2};
  do {
    reset();
    assert(open[order[0]](100, 16));
    // Every later window must reject partial overlap, containment and a
    // one-block intersection. A refusal must leave it available to open.
    for (unsigned at = 1; at < 3; ++at) {
      const Opener next = open[order[at]];
      assert(!next(99, 2) && !next(100, 16) && !next(101, 1));
      assert(!next(99, 18) && !next(115, 2));
      assert(!next(0, 0) && !next(0x100000000ULL, 1));
      assert(!next(0xfffffff0ULL, 32));
      assert(next(100 + at * 16, 16));
      assert(!next(200, 1)); // Open once, even with a disjoint second range.
    }
    assert(hostInWindow(100, 16) && hostInWindow(116, 16) && hostInWindow(132, 16));
    assert(!hostInWindow(99, 1) && !hostInWindow(148, 1));
    assert(!hostInWindow(115, 2) && !hostInWindow(131, 2));
    std::array<uint8_t,8192> bytes{};
    for (uint64_t at : {99ULL, 115ULL, 131ULL, 148ULL}) {
      const unsigned before = writes;
      const uint32_t count = at == 115 || at == 131 ? 2 : 1;
      assert(hostWrite4k(0, at, count, bytes.data()) == kIOReturnBadArgument);
      assert(writes == before);
    }
    assert(hostWrite4k(1, 100, 1, bytes.data()) == kIOReturnBadArgument);
    assert(hostWrite4k(0, 100, 1, bytes.data(), true) == kIOReturnSuccess);
    assert(device[kUcdOffset + 16] == 0x2a && device[kUcdOffset + 17] == 0x08);
    assert(hostSyncCache() == kIOReturnSuccess && device[kUcdOffset + 16] == 0x35);
  } while (std::next_permutation(order, order + 3));
}

static void checkBoardApis()
{
  constexpr uint64_t partition = 16ULL * 1024 * 1024; // 64 GiB, in 4 KiB blocks.
  constexpr uint64_t image = 2ULL * 1024 * 1024;     // 8 GiB root image.
  const uint64_t reserve = uint64_t(testReserveMiB) * 256;
  const char *why = nullptr;
  uint64_t first = 0, count = 0;
  geometry(partition, image);
  assert(!native_ufs_store_open(0, &first, &why));
  assert(!native_ufs_store_open(partition / 4 + 1, &first, &why));
  assert(gStoreRegionBlocks == 0 && !gStoreOpen);
  assert(!native_ufs_aux_open(1, &first, &why));
  if (!testMode) {
    assert(!native_ufs_store_open(131072, &first, &why));
    assert(!native_ufs_store_sync());
  } else {
    assert(native_ufs_store_open(partition / 4, &first, &why));
    assert(first == gStoreGeometry.last + 1 - reserve - partition / 4);
    assert(!native_ufs_store_open(1, &first, &why));
    std::array<uint8_t,4096> bytes{};
    if (testMode == 1) {
      assert(!gStoreOpen && !native_ufs_aux_open(1, &first, &why));
      const unsigned before = writes;
      assert(!native_ufs_store_write(0, 1, bytes.data()) && !native_ufs_store_sync());
      assert(writes == before); // Read-only probing never submits a write/flush.
      assert(native_ufs_store_read(0, 1, bytes.data()));
    } else {
      assert(gStoreOpen);
      assert(!native_ufs_aux_open(65537, &first, &why) && first == 0);
      assert(!gAuxOpen && gAuxRegionBlocks == 0);
      assert(native_ufs_aux_open(1, &first, &why));
      assert(gAuxRegionBlocks == 65536 && first + 65536 == gStoreRegionFirst);
      const uint64_t auxFirst = first;
      assert(!native_ufs_aux_open(0, &first, &why) && first == 0);
      assert(!native_ufs_aux_open(65537, &first, &why) && first == 0);
      assert(native_ufs_aux_open(65536, &first, &why) && first == auxFirst);
      assert(native_ufs_store_write(0, 1, bytes.data()));
      assert(device[kUcdOffset + 17] == 0x08); // FUA survives board wrapper.
      assert(native_ufs_aux_write(65535, 1, bytes.data()));
      assert(device[kUcdOffset + 17] == 0x08);
      assert(!native_ufs_aux_write(65536, 1, bytes.data()));
      assert(!native_ufs_aux_read(65535, 2, bytes.data()));
      assert(!native_ufs_store_write(partition / 4, 1, bytes.data()));
      assert(native_ufs_store_sync() && native_ufs_aux_sync());
    }
  }

  // Root + guard exactly at the store start is allowed; one block less is
  // refused. Test both read-only and writable mode without any device I/O.
  if (testMode) {
    geometry(partition, partition - reserve - 131072 - 1024);
    assert(native_ufs_store_open(131072, &first, &why));
    geometry(partition, partition - reserve - 131072 - 1024 + 1);
    assert(!native_ufs_store_open(131072, &first, &why) && gStoreRegionBlocks == 0);
    geometry(reserve ? reserve : 1024, 0);
    assert(!native_ufs_store_open(1, &first, &why));
  }
  // Oversized tail reserves used to underflow partition-reserve in log_open.
  // In particular a 512 MiB partition must reject the default 1 GiB reserve.
  geometry(131072, 1024);
  const bool smallLog = testLog && reserve >= kLogReserveBlocks + kExportBlocks &&
                        reserve < 131072 && reserve + 2048 <= 131072;
  assert(bool(native_ufs_log_open(&first, &count, &why)) == smallLog);
  geometry(partition, image);
  const bool logExpected = testLog && reserve >= kLogReserveBlocks + kExportBlocks;
  assert(bool(native_ufs_log_open(&first, &count, &why)) == logExpected);
  if (logExpected) {
    assert(first == gStoreGeometry.last + 1 - kLogReserveBlocks && count == kLogReserveBlocks);
    assert(native_ufs_export_blocks() == kExportBlocks);
    assert(!native_ufs_log_open(&first, &count, &why));
  }
  puts("PASS: production persistence modes, quarter/guard/reserve policy, aux capacity and all window opening orders; transport is a host fixture");
}

int main(int argc, char **argv)
{
  assert(argc == 4);
  testMode = uint32_t(std::strtoul(argv[1], nullptr, 10));
  testReserveMiB = uint32_t(std::strtoul(argv[2], nullptr, 10));
  testLog = uint32_t(std::strtoul(argv[3], nullptr, 10));
  checkWindowOrders();
  checkBoardApis();
  return 0;
}
